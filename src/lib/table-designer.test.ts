import { describe, expect, it, vi } from "vitest";
vi.mock("sql.js/dist/sql-wasm.wasm?url", () => ({
  default: "node_modules/sql.js/dist/sql-wasm.wasm",
}));
import { buildTablePlan, newField, newTableDesign } from "./table-designer";
import * as api from "./api";

describe("table designer SQL plans", () => {
  it("builds a single MySQL CREATE with fields, indexes, foreign keys, checks and escaped comments", () => {
    const design = newTableDesign("mysql", "app");
    design.name = "orders";
    const email = {
      ...newField("mysql", "email"),
      type: "varchar",
      length: "120",
      defaultKind: "value" as const,
      defaultValue: "it's \\ a test",
      comment: "Email's value",
    };
    const user = newField("mysql", "user_id");
    design.fields.push(email, user);
    design.indexes.push({
      id: "index",
      name: "unique_email",
      unique: true,
      fields: [email.id],
    });
    design.foreignKeys.push({
      id: "fk",
      name: "orders_user",
      fields: [user.id],
      referenceSchema: "app",
      referenceTable: "users",
      referenceFields: "id",
      onDelete: "CASCADE",
      onUpdate: "NO ACTION",
    });
    design.checks.push({
      id: "check",
      name: "positive_id",
      expression: "user_id > 0",
    });
    design.charset = "utf8mb4";
    design.comment = "Order's data";
    const plan = buildTablePlan(design, "mysql", "app");
    expect(plan.statements).toHaveLength(1);
    expect(plan.sql).toContain("`id` int NOT NULL AUTO_INCREMENT");
    expect(plan.sql).toContain("PRIMARY KEY (`id`)");
    expect(plan.sql).toContain("UNIQUE INDEX `unique_email` (`email`)");
    expect(plan.sql).toContain("REFERENCES `app`.`users` (`id");
    expect(plan.sql).toContain("CHECK (user_id > 0)");
    expect(plan.sql).toContain("COMMENT='Order''s data'");
    expect(plan.sql).toContain("DEFAULT 'it''s \\\\ a test'");
  });
  it("quotes identifiers and rejects type/expression injection", () => {
    const design = newTableDesign("mysql", "app");
    design.name = "x`; DROP TABLE users; --";
    expect(buildTablePlan(design, "mysql", "app").sql).toContain(
      "`x``; DROP TABLE users; --`",
    );
    design.fields[0].type = "int); DROP TABLE users; --";
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "unsupported type",
    );
    design.fields[0] = {
      ...newField("mysql", "clock"),
      type: "timestamp",
      defaultKind: "expression",
      defaultValue: "NOW(); DROP TABLE users",
    };
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "choose CURRENT_TIMESTAMP",
    );
  });
  it("rejects duplicate fields and invalid type, default, identity, and foreign key settings", () => {
    const design = newTableDesign("mysql", "app");
    design.name = "valid";
    design.fields.push(newField("mysql", "ID"));
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "Duplicate field",
    );
    design.fields = [{ ...newField("mysql", "name"), type: "varchar" }];
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "length is required",
    );
    design.fields = [
      {
        ...newField("mysql", "qty"),
        defaultKind: "value",
        defaultValue: "bad",
      },
    ];
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "whole number",
    );
    design.fields = [
      { ...newField("mysql", "qty"), defaultKind: "null", notNull: true },
    ];
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "cannot default to NULL",
    );
    design.fields = [
      { ...newField("mysql", "qty"), type: "text", autoIncrement: true },
    ];
    expect(() => buildTablePlan(design, "mysql", "app")).toThrow(
      "auto increment requires",
    );
  });
  it("generates PostgreSQL identity, standalone indexes and comments with safe literals", () => {
    const design = newTableDesign("postgres", "app");
    design.name = "events";
    design.indexes = [
      {
        id: "ix",
        name: "events_id",
        unique: false,
        fields: [design.fields[0].id],
      },
    ];
    design.comment = "one's \\ purpose";
    const plan = buildTablePlan(design, "postgres", "app");
    expect(plan.sql).toContain(
      '"id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY',
    );
    expect(plan.statements[1]).toBe(
      'CREATE INDEX "events_id" ON "public"."events" ("id");',
    );
    expect(plan.statements[2]).toContain("E'one''s \\\\ purpose'");
  });
  it("creates a real SQLite table with defaults, composite indexes and checks; preserves existing tables", async () => {
    const design = newTableDesign("sqlite", "workspace");
    design.name = "designer_people";
    const name = { ...newField("sqlite", "name"), type: "TEXT", notNull: true };
    const count = {
      ...newField("sqlite", "qty"),
      type: "INTEGER",
      defaultKind: "value" as const,
      defaultValue: "2",
    };
    design.fields.push(name, count);
    design.indexes.push({
      id: "ix",
      name: "designer_people_name",
      unique: true,
      fields: [name.id, count.id],
    });
    design.checks.push({
      id: "ck",
      name: "positive_qty",
      expression: "qty >= 0",
    });
    await api.createTable("demo", "workspace", design);
    await api.execute(
      "demo",
      "INSERT INTO designer_people(name) VALUES ('Ada')",
    );
    expect(
      (await api.execute("demo", "SELECT name, qty FROM designer_people")).rows,
    ).toEqual([["Ada", 2]]);
    await expect(
      api.execute(
        "demo",
        "INSERT INTO designer_people(name, qty) VALUES ('Bad', -1)",
      ),
    ).rejects.toThrow();
    await expect(
      api.createTable("demo", "workspace", design),
    ).rejects.toThrow();
    expect(
      (await api.execute("demo", "SELECT COUNT(*) FROM designer_people")).rows,
    ).toEqual([[1]]);
  });
  it("rolls back the table when a follow-up index fails", async () => {
    await api.execute(
      "demo",
      "CREATE TABLE designer_existing(id INTEGER); CREATE INDEX designer_taken ON designer_existing(id)",
    );
    const design = newTableDesign("sqlite", "workspace");
    design.name = "designer_failed";
    design.indexes.push({
      id: "ix",
      name: "designer_taken",
      unique: false,
      fields: [design.fields[0].id],
    });
    await expect(
      api.createTable("demo", "workspace", design),
    ).rejects.toThrow();
    expect(
      (
        await api.execute(
          "demo",
          "SELECT name FROM sqlite_master WHERE name = 'designer_failed'",
        )
      ).rows,
    ).toHaveLength(0);
  });
  it("creates and enforces a foreign key in SQLite", async () => {
    await api.execute(
      "demo",
      "PRAGMA foreign_keys = ON; CREATE TABLE designer_parent(id INTEGER PRIMARY KEY); INSERT INTO designer_parent VALUES(1)",
    );
    const design = newTableDesign("sqlite", "workspace");
    design.name = "designer_child";
    const parent = newField("sqlite", "parent_id");
    design.fields.push(parent);
    design.foreignKeys.push({
      id: "fk",
      name: "child_parent",
      fields: [parent.id],
      referenceSchema: "",
      referenceTable: "designer_parent",
      referenceFields: "id",
      onDelete: "CASCADE",
      onUpdate: "NO ACTION",
    });
    await api.createTable("demo", "workspace", design);
    await api.execute(
      "demo",
      "INSERT INTO designer_child(parent_id) VALUES (1)",
    );
    await expect(
      api.execute("demo", "INSERT INTO designer_child(parent_id) VALUES (9)"),
    ).rejects.toThrow();
    await api.execute("demo", "DELETE FROM designer_parent WHERE id = 1");
    expect(
      (await api.execute("demo", "SELECT * FROM designer_child")).rows,
    ).toHaveLength(0);
  });
});

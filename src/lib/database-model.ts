import * as api from "./api";
import type {
  ColumnInfo,
  Driver,
  ForeignKeyInfo,
  IndexInfo,
  Session,
  TableInfo,
} from "../types";
import { qualifiedName, quoteIdentifier } from "./sql";
export interface ModelTable {
  table: TableInfo;
  columns: ColumnInfo[];
  indexes: IndexInfo[];
  keys: ForeignKeyInfo[];
  x: number;
  y: number;
}
export interface DatabaseModel {
  version: 1;
  driver: Driver;
  database: string;
  tables: ModelTable[];
}
export const modelTableKey = (table: TableInfo) =>
  JSON.stringify([table.schema, table.name]);
export async function reverseDatabase(
  session: Session,
  database: string,
): Promise<DatabaseModel> {
  const tree = await api.schema(session.id, database);
  const tables = tree.tables.filter((t) => t.kind === "table");
  if (tables.length > 100)
    throw new Error(
      "Models support up to 100 tables. Use a connection focused on a smaller database.",
    );
  const result: ModelTable[] = [];
  // Bound metadata concurrency to the connection pool size.
  for (let start = 0; start < tables.length; start += 3) {
    result.push(
      ...(await Promise.all(
        tables.slice(start, start + 3).map(async (table, i) => {
          const columns = await api.columns(session.id, table, database);
          const indexes = await api.listIndexes(session.id, table, database);
          const keys = await api.foreignKeys(session.id, table, database);
          // ER modeling reads metadata only, never table records or COUNT(*).
          // SQLite INTEGER PRIMARY KEY is not returned by pragma_index_list.
          if (
            session.config.driver === "sqlite" &&
            !indexes.some((index) => index.primary)
          ) {
            const primary = await api.execute(
              session.id,
              `SELECT name FROM pragma_table_info('${table.name.replaceAll("'", "''")}') WHERE pk > 0 ORDER BY pk`,
              database,
            );
            if (primary.rows.length)
              indexes.unshift({
                name: "PRIMARY",
                columns: primary.rows.map((row) => String(row[0])),
                primary: true,
                unique: true,
              });
          }
          const primary = indexes.find((index) => index.primary)?.columns ?? [];
          columns.forEach((column) => {
            if (primary.includes(column.name)) column.nullable = false;
          });
          const position = start + i;
          return {
            table,
            columns,
            indexes,
            keys,
            x: 24 + (position % 4) * 260,
            y: 24 + Math.floor(position / 4) * 280,
          };
        }),
      )),
    );
  }
  return {
    version: 1,
    driver: session.config.driver,
    database,
    tables: result,
  };
}
function checkedType(type: string) {
  if (
    !/^[a-zA-Z_][a-zA-Z0-9_ ]*(?:\(\d+(?:,\s*\d+)?\))?(?:\[\])?$/.test(
      type.trim(),
    )
  )
    throw new Error(
      `Type ${type} requires the table designer (enum, domain and custom types are not generated by the model).`,
    );
  return type;
}
function columnSql(column: ColumnInfo, driver: Driver) {
  if (!column.name.trim() || column.name.includes("\0"))
    throw new Error("Each field needs a valid name.");
  return `${quoteIdentifier(column.name, driver)} ${checkedType(column.data_type)}${column.nullable ? "" : " NOT NULL"}`;
}
export function forwardModel(
  model: DatabaseModel,
  tables = model.tables,
): string {
  const driver = model.driver;
  const parts: string[] = [];
  if (driver === "postgres")
    for (const schema of new Set(
      tables.map((t) => t.table.schema).filter(Boolean),
    ))
      parts.push(
        `CREATE SCHEMA IF NOT EXISTS ${quoteIdentifier(schema, driver)};`,
      );
  for (const item of tables) {
    if (
      !item.table.name.trim() ||
      !item.columns.length ||
      new Set(item.columns.map((c) => c.name)).size !== item.columns.length
    )
      throw new Error("Every table needs a name and unique fields.");
    const primary = item.indexes.find((i) => i.primary);
    const fields = item.columns.map((c) => columnSql(c, driver));
    if (primary?.columns.length)
      fields.push(
        `PRIMARY KEY (${primary.columns.map((c) => quoteIdentifier(c, driver)).join(", ")})`,
      );
    if (driver === "sqlite")
      for (const key of item.keys)
        fields.push(
          `FOREIGN KEY (${key.columns.map((c) => quoteIdentifier(c, driver)).join(", ")}) REFERENCES ${quoteIdentifier(key.referenced_table.name, driver)} (${key.referenced_columns.map((c) => quoteIdentifier(c, driver)).join(", ")})`,
        );
    parts.push(
      `CREATE TABLE ${qualifiedName(item.table, driver)} (\n  ${fields.join(",\n  ")}\n);`,
    );
    for (const index of item.indexes.filter((i) => !i.primary)) {
      if (
        index.columns.some(
          (c) => !item.columns.some((field) => field.name === c),
        )
      )
        throw new Error(
          `Expression index ${index.name} requires the table designer.`,
        );
      parts.push(
        `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${quoteIdentifier(index.name, driver)} ON ${qualifiedName(item.table, driver)} (${index.columns.map((c) => quoteIdentifier(c, driver)).join(", ")});`,
      );
    }
  }
  if (driver !== "sqlite")
    for (const item of tables)
      for (const key of item.keys)
        parts.push(
          `ALTER TABLE ${qualifiedName(item.table, driver)} ADD CONSTRAINT ${quoteIdentifier(key.name, driver)} FOREIGN KEY (${key.columns.map((c) => quoteIdentifier(c, driver)).join(", ")}) REFERENCES ${qualifiedName(key.referenced_table, driver)} (${key.referenced_columns.map((c) => quoteIdentifier(c, driver)).join(", ")});`,
        );
  return parts.join("\n\n");
}
/** Additive synchronization never drops an existing field, constraint or record. */
export function syncModel(
  model: DatabaseModel,
  live: DatabaseModel,
): { sql: string; notes: string[] } {
  if (model.driver !== live.driver)
    throw new Error("Model and destination database engines must match.");
  const parts: string[] = [],
    notes: string[] = [];
  const missing = model.tables.filter(
    (t) =>
      !live.tables.some(
        (existing) => modelTableKey(t.table) === modelTableKey(existing.table),
      ),
  );
  if (missing.length) parts.push(forwardModel(model, missing));
  for (const item of model.tables) {
    const existing = live.tables.find(
      (t) => modelTableKey(t.table) === modelTableKey(item.table),
    );
    if (!existing) continue;
    for (const column of item.columns) {
      const before = existing.columns.find((c) => c.name === column.name);
      if (!before) {
        if (!column.nullable)
          notes.push(
            `${item.table.name}.${column.name}: adding NOT NULL may fail if existing records have no default; use the table designer to supply a default.`,
          );
        parts.push(
          `ALTER TABLE ${qualifiedName(item.table, model.driver)} ADD COLUMN ${columnSql(column, model.driver)};`,
        );
      } else if (
        before.data_type.toLowerCase() !== column.data_type.toLowerCase() ||
        before.nullable !== column.nullable
      )
        notes.push(
          `${item.table.name}.${column.name}: type/nullability differs. Use Design Table to migrate existing fields while preserving defaults and generated properties.`,
        );
    }
    for (const index of item.indexes.filter((index) => !index.primary)) {
      const before = existing.indexes.find((i) => i.name === index.name);
      if (!before) {
        if (
          index.columns.some(
            (name) => !item.columns.some((c) => c.name === name),
          )
        ) {
          notes.push(
            `${item.table.name}.${index.name}: expression index requires Design Table.`,
          );
          continue;
        }
        parts.push(
          `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${quoteIdentifier(index.name, model.driver)} ON ${qualifiedName(item.table, model.driver)} (${index.columns.map((c) => quoteIdentifier(c, model.driver)).join(", ")});`,
        );
      } else if (
        before.unique !== index.unique ||
        JSON.stringify(before.columns) !== JSON.stringify(index.columns)
      )
        notes.push(
          `${item.table.name}.${index.name}: index differs; existing index retained.`,
        );
    }
    for (const key of item.keys) {
      const before = existing.keys.find((k) => k.name === key.name);
      if (!before) {
        if (model.driver === "sqlite") {
          notes.push(
            `${item.table.name}.${key.name}: adding a foreign key to an existing SQLite table requires rebuilding it in Design Table.`,
          );
          continue;
        }
        parts.push(
          `ALTER TABLE ${qualifiedName(item.table, model.driver)} ADD CONSTRAINT ${quoteIdentifier(key.name, model.driver)} FOREIGN KEY (${key.columns.map((c) => quoteIdentifier(c, model.driver)).join(", ")}) REFERENCES ${qualifiedName(key.referenced_table, model.driver)} (${key.referenced_columns.map((c) => quoteIdentifier(c, model.driver)).join(", ")});`,
        );
      } else if (JSON.stringify(before) !== JSON.stringify(key))
        notes.push(
          `${item.table.name}.${key.name}: foreign key differs; existing relationship retained.`,
        );
    }
    for (const column of existing.columns)
      if (!item.columns.some((c) => c.name === column.name))
        notes.push(
          `${item.table.name}.${column.name}: retained in the database; additive sync does not drop fields.`,
        );
  }
  return { sql: parts.join("\n\n"), notes };
}
export function parseModel(text: string): DatabaseModel {
  const data = JSON.parse(text);
  const validName = (value: unknown): value is string =>
    typeof value === "string" && value.length <= 256 && !value.includes("\0");
  const list = (value: unknown): value is string[] =>
    Array.isArray(value) && value.length <= 500 && value.every(validName);
  const table = (value: any) =>
    value &&
    validName(value.name) &&
    !!value.name &&
    validName(value.schema) &&
    value.kind === "table";
  if (
    data?.version !== 1 ||
    !["mysql", "postgres", "sqlite"].includes(data.driver) ||
    !validName(data.database) ||
    !Array.isArray(data.tables) ||
    data.tables.length > 100
  )
    throw new Error("Choose a DBde model version 1.");
  const seen = new Set<string>();
  for (const item of data.tables) {
    if (
      !table(item?.table) ||
      !Array.isArray(item.columns) ||
      !item.columns.length ||
      item.columns.length > 500 ||
      !Array.isArray(item.indexes) ||
      item.indexes.length > 500 ||
      !Array.isArray(item.keys) ||
      item.keys.length > 500 ||
      !Number.isFinite(item.x) ||
      !Number.isFinite(item.y) ||
      item.x < 0 ||
      item.y < 0 ||
      item.x > 100000 ||
      item.y > 100000
    )
      throw new Error("Invalid model table.");
    const id = modelTableKey(item.table);
    if (seen.has(id)) throw new Error("Duplicate model table.");
    seen.add(id);
    const fields = new Set<string>();
    for (const column of item.columns) {
      if (
        !validName(column?.name) ||
        !column.name ||
        fields.has(column.name) ||
        !validName(column.data_type) ||
        !column.data_type ||
        typeof column.nullable !== "boolean"
      )
        throw new Error("Invalid model field.");
      fields.add(column.name);
    }
    for (const index of item.indexes)
      if (
        !validName(index?.name) ||
        !list(index.columns) ||
        !index.columns.length ||
        typeof index.primary !== "boolean" ||
        typeof index.unique !== "boolean"
      )
        throw new Error("Invalid model index.");
    for (const key of item.keys)
      if (
        !validName(key?.name) ||
        !list(key.columns) ||
        !key.columns.length ||
        !key.columns.every((name: string) => fields.has(name)) ||
        !table(key.referenced_table) ||
        !list(key.referenced_columns) ||
        key.columns.length !== key.referenced_columns.length
      )
        throw new Error("Invalid model relationship.");
  }
  return data;
}
export function renameModelField(
  model: DatabaseModel,
  tableIndex: number,
  fieldIndex: number,
  name: string,
): DatabaseModel {
  const target = model.tables[tableIndex];
  const before = target.columns[fieldIndex].name;
  return {
    ...model,
    tables: model.tables.map((item, i) => ({
      ...item,
      columns:
        i === tableIndex
          ? item.columns.map((c, n) => (n === fieldIndex ? { ...c, name } : c))
          : item.columns,
      indexes:
        i === tableIndex
          ? item.indexes.map((index) => ({
              ...index,
              columns: index.columns.map((c) => (c === before ? name : c)),
            }))
          : item.indexes,
      keys: item.keys.map((key) => ({
        ...key,
        columns:
          i === tableIndex
            ? key.columns.map((c) => (c === before ? name : c))
            : key.columns,
        referenced_columns:
          modelTableKey(key.referenced_table) === modelTableKey(target.table)
            ? key.referenced_columns.map((c) => (c === before ? name : c))
            : key.referenced_columns,
      })),
    })),
  };
}
